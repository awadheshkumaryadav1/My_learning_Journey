//for 
for(let i=0;i<5;i++){
    console.log(i);
}
//while
console.log("while loop");
let i=0;
while(i<4){
    console.log(i);
    i++;
}

console.log("do while loop");
let j=0;
do{
    console.log(j);
    j++;
}
while(j>3);

//for of (array)
console.log("for of loop");
let arr=[1,2,3,4,5];
for(let num of arr){
    console.log(num);
}